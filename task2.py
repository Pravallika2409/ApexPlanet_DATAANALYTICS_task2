import sqlite3
import pandas as pd

# Create an in-memory SQL database
conn = sqlite3.connect(":memory:")

# Load the cleaned dataset into a SQL table
df.to_sql("sales", conn, index=False, if_exists="replace")

print("SQL database created successfully!")
print("Table name: sales")

# Check the table
pd.read_sql_query(
    "SELECT * FROM sales LIMIT 5;",
    conn
)

query1 = """
SELECT
    Product,
    SUM(Total_Sales) AS Total_Sales,
    SUM(Quantity) AS Total_Quantity
FROM sales
GROUP BY Product
ORDER BY Total_Sales DESC
LIMIT 5;
"""

result1 = pd.read_sql_query(query1, conn)

print("TOP 5 PRODUCTS BY TOTAL SALES")
display(result1.round(2))

query2 = """
SELECT
    strftime('%Y-%m', Order_Date) AS Month,
    ROUND(SUM(Total_Sales), 2) AS Total_Sales
FROM sales
GROUP BY strftime('%Y-%m', Order_Date)
ORDER BY Month;
"""

result2 = pd.read_sql_query(query2, conn)

print("MONTHLY SALES ANALYSIS")
display(result2)

query3 = """
SELECT
    Category,
    ROUND(SUM(Total_Sales), 2) AS Total_Sales,
    SUM(Quantity) AS Total_Quantity,
    COUNT(*) AS Total_Records
FROM sales
GROUP BY Category
ORDER BY Total_Sales DESC;
"""

result3 = pd.read_sql_query(query3, conn)

print("SALES BY PRODUCT CATEGORY")
display(result3)

query4 = """
SELECT
    City,
    ROUND(SUM(Total_Sales), 2) AS Total_Sales,
    COUNT(*) AS Total_Records
FROM sales
GROUP BY City
ORDER BY Total_Sales DESC;
"""

result4 = pd.read_sql_query(query4, conn)

print("CITY-WISE SALES ANALYSIS")
display(result4)

query5 = """
SELECT
    Customer_ID,
    Customer_Name,
    ROUND(SUM(Total_Sales), 2) AS Total_Sales,
    SUM(Quantity) AS Total_Quantity,
    COUNT(*) AS Total_Records
FROM sales
GROUP BY Customer_ID, Customer_Name
ORDER BY Total_Sales DESC
LIMIT 5;
"""

result5 = pd.read_sql_query(query5, conn)

print("TOP 5 CUSTOMERS BY SALES")
display(result5)

query6 = """
SELECT
    Product,
    ROUND(AVG(Total_Sales), 2) AS Average_Sales,
    SUM(Quantity) AS Total_Quantity,
    COUNT(*) AS Total_Records
FROM sales
GROUP BY Product
ORDER BY Average_Sales DESC;
"""

result6 = pd.read_sql_query(query6, conn)

print("AVERAGE SALES BY PRODUCT")
display(result6)

query7 = """
SELECT
    Gender,
    ROUND(SUM(Total_Sales), 2) AS Total_Sales,
    ROUND(AVG(Total_Sales), 2) AS Average_Sales,
    COUNT(*) AS Total_Records,
    SUM(Quantity) AS Total_Quantity
FROM sales
GROUP BY Gender
ORDER BY Total_Sales DESC;
"""

result7 = pd.read_sql_query(query7, conn)

