import pandas as pd
import matplotlib.pyplot as plt

df = pd.read_csv("/content/cleaned_sales_dataset.csv")

print("Dataset loaded successfully!")
print("Dataset shape:", df.shape)
display(df.head())

# Sales analysis by gender

gender_sales = (
    df.groupby("Gender")
    .agg(
        Total_Sales=("Total_Sales", "sum"),
        Total_Records=("Order_ID", "count")
    )
    .sort_values("Total_Sales", ascending=False)
)

print("SALES BY GENDER")
display(gender_sales.round(2))

# Bar chart
gender_sales["Total_Sales"].plot(
    kind="bar",
    figsize=(7, 5)
)

plt.title("Total Sales by Gender")
plt.xlabel("Gender")
plt.ylabel("Total Sales")
plt.xticks(rotation=0)
plt.tight_layout()
plt.show()

# City-wise sales analysis

city_sales = (
    df.groupby("City")
    .agg(
        Total_Sales=("Total_Sales", "sum"),
        Total_Records=("Order_ID", "count")
    )
    .sort_values("Total_Sales", ascending=False)
)

print("SALES BY CITY")
display(city_sales.round(2))

# Bar chart
city_sales["Total_Sales"].plot(
    kind="bar",
    figsize=(9, 5)
)

plt.title("Total Sales by City")
plt.xlabel("City")
plt.ylabel("Total Sales")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()

# Monthly sales analysis

df["Order_Date"] = pd.to_datetime(df["Order_Date"])

df["Month"] = df["Order_Date"].dt.to_period("M").astype(str)

monthly_sales = (
    df.groupby("Month")["Total_Sales"]
    .sum()
    .sort_index()
)

print("MONTHLY SALES")
display(monthly_sales.to_frame("Total_Sales").round(2))

# Line chart
monthly_sales.plot(
    kind="line",
    marker="o",
    figsize=(10, 5)
)

plt.title("Monthly Sales Trend - 2025")
plt.xlabel("Month")
plt.ylabel("Total Sales")
plt.xticks(rotation=45)
plt.grid(True)
plt.tight_layout()
plt.show()

